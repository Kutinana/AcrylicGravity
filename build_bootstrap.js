const fs = require('node:fs');
const path = require('node:path');

const ROOT = __dirname;
const { version } = require('./package.json');

function buildBootstrap() {
  const css = fs.readFileSync(path.join(ROOT, 'style.css'), 'utf8');
  const injector = fs.readFileSync(path.join(ROOT, 'injector.js'), 'utf8');
  const background = path.join(ROOT, 'assets', 'background.dataurl.txt');
  const dataUri = fs.existsSync(background) ? fs.readFileSync(background, 'utf8').trim() : 'none';
  const bundle = `// Generated by build_bootstrap.js. Edit style.css and injector.js instead.
(function () {
  window.__AG_VERSION = ${JSON.stringify(version)};
  window.__AG_BG_DATA_URI = ${JSON.stringify(dataUri)};
  window.__AG_CSS_CONTENT = ${JSON.stringify(css)};
  ${injector}
})();
`;
  const target = path.join(ROOT, 'bootstrap.js');
  fs.writeFileSync(target, bundle);
  console.log(`Generated bootstrap.js (${Buffer.byteLength(bundle)} bytes).`);
  return target;
}

function syncInstalled(target) {
  if (!process.env.LOCALAPPDATA) throw new Error('LOCALAPPDATA is unavailable.');
  const resources = path.join(process.env.LOCALAPPDATA, 'Programs', 'antigravity', 'resources');
  const installed = path.join(resources, 'app', 'dist', 'bootstrap.js');
  if (fs.existsSync(installed)) {
    fs.copyFileSync(target, installed);
    console.log('Updated the installed theme bundle.');
  } else {
    console.log('No folder installation found. Reinstall to update an ASAR installation.');
  }
}

if (require.main === module) {
  try {
    const target = buildBootstrap();
    if (process.argv.includes('--sync')) syncInstalled(target);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { buildBootstrap, syncInstalled };
